"""Describe a landscape snapshot: distributions, and where the flagged repositories sit in them.

    uv run tools/describe_snapshot.py [--snapshot DIR] [--out FILE]

Reads `repos.tsv` of a snapshot (default: the newest under kb-kg/landscape/) and writes a Markdown report
(default: kb-kg/experiments/x1-snapshot-distributions/README.md). It uses no model and no network. It is
descriptive only: it cannot say whether any repository's growth is organic.
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

METRICS = (
    ("stars", "Stars"),
    ("stars_per_day", "Stars per day of age"),
    ("forks_per_100_stars", "Forks per 100 stars"),
    ("open_issues", "Open issues and pull requests"),
    ("contributors", "Contributors (enriched repositories only)"),
    ("days_since_push", "Days since the last push"),
)
PERCENTILES = (10, 25, 50, 75, 90, 99)


def percentile(sorted_values: list[float], p: float) -> float:
    """Linear-interpolation percentile of an ascending list (the common 'inclusive' definition)."""
    if not sorted_values:
        raise ValueError("no values")
    if len(sorted_values) == 1:
        return sorted_values[0]
    pos = (len(sorted_values) - 1) * p / 100
    low = int(pos)
    high = min(low + 1, len(sorted_values) - 1)
    return sorted_values[low] + (sorted_values[high] - sorted_values[low]) * (pos - low)


def percentile_rank(sorted_values: list[float], x: float) -> float:
    """Share of values less than or equal to x, as a percentage."""
    if not sorted_values:
        raise ValueError("no values")
    return 100 * sum(1 for v in sorted_values if v <= x) / len(sorted_values)


def number(text: str) -> float | None:
    text = (text or "").strip()
    if not text:
        return None
    try:
        return float(text)
    except ValueError:
        return None


def load(tsv: Path) -> list[dict[str, str]]:
    with tsv.open(encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))


def column(rows: list[dict[str, str]], key: str) -> list[float]:
    return sorted(v for r in rows if (v := number(r.get(key, ""))) is not None)


def fmt(x: float) -> str:
    if abs(x) >= 100:
        return f"{x:,.0f}"
    return f"{x:,.2f}".rstrip("0").rstrip(".")


def newest_snapshot(root: Path) -> Path:
    candidates = sorted(p for p in root.glob("*-github") if (p / "repos.tsv").exists())
    if not candidates:
        raise FileNotFoundError(f"no snapshot with a repos.tsv under {root}")
    return candidates[-1]


def render(snapshot: str, rows: list[dict[str, str]]) -> str:
    ranked = [r for r in rows if r.get("table") == "ranked"]
    flagged = [r for r in ranked if "fast-growth" in (r.get("flags") or "")]
    out = [
        "# X1: Describing the snapshot",
        "",
        "<!-- Generated by tools/describe_snapshot.py. Do not edit by hand. -->",
        "",
        f"Snapshot: `{snapshot}`. {len(rows)} repositories were found; {len(ranked)} are *ranked* (pushed within "
        f"90 days and not archived), and the distributions below describe those. {len(flagged)} carry the "
        "`fast-growth` flag (stars per day of age at or above the threshold in `tools/snapshot/queries.toml`).",
        "",
        "**This is a description, not a test.** The repositories are what the snapshot's searches returned, with "
        "a stars floor and a cap per query; they are not a random sample of GitHub, and a percentile here means "
        "\"among these\". Nothing below can tell organic growth from inflated growth, and nothing is concluded "
        "about any repository.",
        "",
        "## Distribution of the ranked repositories",
        "",
        "| Metric | n | " + " | ".join(f"p{p}" for p in PERCENTILES) + " | max |",
        "|---|---|" + "---|" * (len(PERCENTILES) + 1),
    ]
    for key, label in METRICS:
        vals = column(ranked, key)
        if not vals:
            out.append(f"| {label} | 0 |" + " |" * (len(PERCENTILES) + 1))
            continue
        cells = [fmt(percentile(vals, p)) for p in PERCENTILES] + [fmt(vals[-1])]
        out.append(f"| {label} | {len(vals)} | " + " | ".join(cells) + " |")
    out += [
        "",
        "## Where the fast-growth repositories sit",
        "",
        "Each cell is the value, then its percentile rank among the ranked repositories (the share at or below "
        "it). A blank means the value is not recorded for that repository.",
        "",
        "| Repository | Category | " + " | ".join(label for _, label in METRICS) + " |",
        "|---|---|" + "---|" * len(METRICS),
    ]
    sorted_cols = {key: column(ranked, key) for key, _ in METRICS}
    for r in sorted(flagged, key=lambda r: -(number(r.get("stars_per_day", "")) or 0)):
        cells = []
        for key, _ in METRICS:
            v = number(r.get(key, ""))
            if v is None or not sorted_cols[key]:
                cells.append("")
            else:
                cells.append(f"{fmt(v)} (p{percentile_rank(sorted_cols[key], v):.0f})")
        out.append(f"| {r['full_name']} | {r['category']} | " + " | ".join(cells) + " |")
    out += [
        "",
        "## What this can and cannot show",
        "",
        "- It shows how far from the middle of this set each flagged repository is on each measure.",
        "- It does not show why. A repository can be far out on every measure because of a launch, a "
        "newsletter, a trend, a list or a tutorial, and also for other reasons.",
        "- Contributors are recorded only for the repositories the tool enriched (the top of each category and "
        "the watchlist), so that row describes a subset.",
        "- Percentiles depend on the snapshot's queries. Re-run the tool on a later snapshot to see how the "
        "picture moves.",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--snapshot", help="snapshot directory (default: the newest under kb-kg/landscape/)")
    parser.add_argument("--out", default="kb-kg/experiments/x1-snapshot-distributions/README.md")
    args = parser.parse_args(argv)
    try:
        snap = Path(args.snapshot) if args.snapshot else newest_snapshot(Path("kb-kg/landscape"))
        rows = load(snap / "repos.tsv")
    except (FileNotFoundError, OSError) as err:
        print(f"describe_snapshot: {err}", file=sys.stderr)
        return 2
    text = render(snap.name, rows)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"describe_snapshot: wrote {out} from {snap.name} ({len(rows)} repositories)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
