"""Generate kb-kg/projects/README.md from the front matter of the entries.

    uv run tools/build_projects_index.py            write the index
    uv run tools/build_projects_index.py --check    exit 1 if the index on disk is out of date

An entry is a Markdown file in kb-kg/projects/ that starts with a front matter block holding at least
`slug`, `repo`, `tier` and `category`. Files whose name starts with an underscore (the template) are
skipped. The index is derived data: never edit it by hand.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

CATEGORIES = ("core", "agent-memory", "markdown-kb", "adjacent")
CATEGORY_NOTES = {
    "core": "GraphRAG frameworks, KG construction from text, KG querying",
    "agent-memory": "memory layers and temporal knowledge graphs for agents",
    "markdown-kb": "Markdown-native and \"LLM wiki\" knowledge bases",
    "adjacent": "code knowledge graphs, graph databases, RAG platforms",
}
TIERS = ("deep", "card")
REQUIRED = ("slug", "repo", "tier", "category")


class EntryError(ValueError):
    """An entry whose front matter cannot be used."""


def parse_entry(path: Path) -> dict[str, str]:
    """Read the front matter and the first heading of one entry."""
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        raise EntryError(f"{path.name}: no front matter")
    meta: dict[str, str] = {}
    end = None
    for i, line in enumerate(lines[1:], start=1):
        if line.strip() == "---":
            end = i
            break
        if ":" in line:
            key, _, value = line.partition(":")
            meta[key.strip()] = value.strip()
    if end is None:
        raise EntryError(f"{path.name}: front matter is not closed")
    missing = [k for k in REQUIRED if not meta.get(k)]
    if missing:
        raise EntryError(f"{path.name}: front matter lacks {', '.join(missing)}")
    if meta["slug"] != path.stem:
        raise EntryError(f"{path.name}: slug {meta['slug']!r} does not match the file name")
    if meta["category"] not in CATEGORIES:
        raise EntryError(f"{path.name}: unknown category {meta['category']!r}")
    if meta["tier"] not in TIERS:
        raise EntryError(f"{path.name}: unknown tier {meta['tier']!r}")
    title = next((ln[2:].strip() for ln in lines[end + 1 :] if ln.startswith("# ")), None)
    if not title:
        raise EntryError(f"{path.name}: no top-level heading")
    meta["title"] = title
    meta["file"] = path.name
    return meta


def load_entries(directory: Path) -> list[dict[str, str]]:
    # A slug must equal its file stem and stems are unique in a directory, so slugs cannot collide.
    return [
        parse_entry(p)
        for p in sorted(directory.glob("*.md"))
        if not p.name.startswith("_") and p.name != "README.md"
    ]


def sort_key(entry: dict[str, str]) -> tuple[int, str]:
    return (TIERS.index(entry["tier"]), entry["title"].lower())


def render(entries: list[dict[str, str]]) -> str:
    deep = sum(e["tier"] == "deep" for e in entries)
    card = len(entries) - deep
    out = [
        "# Project entries",
        "",
        "<!-- Generated by tools/build_projects_index.py from the entries' front matter. Do not edit by hand. -->",
        "",
        f"{len(entries)} entries: {deep} deep and {card} cards. A **deep** entry reads the code and documentation "
        "and runs to several thousand words; a **card** is one page from the README, the repository metadata and "
        "the licence file. Both follow [`_TEMPLATE.md`](_TEMPLATE.md). Each entry carries its own snapshot time: "
        "star counts and dates in it are as of that time, and stars are signals, not verdicts.",
        "",
    ]
    for category in CATEGORIES:
        group = sorted((e for e in entries if e["category"] == category), key=sort_key)
        note = CATEGORY_NOTES[category]
        out += [f"## {category} ({len(group)})", "", note[0].upper() + note[1:] + ".", ""]
        out += ["| Project | Repository | Tier | Snapshot |", "|---|---|---|---|"]
        for e in group:
            repo_url = f"https://github.com/{e['repo']}"
            snap = e.get("snapshot", "unstated")
            out.append(f"| [{e['title']}]({e['file']}) | [{e['repo']}]({repo_url}) | {e['tier']} | {snap} |")
        out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the index on disk is out of date")
    parser.add_argument("--dir", default="kb-kg/projects", help="entries directory (default kb-kg/projects)")
    args = parser.parse_args(argv)
    directory = Path(args.dir)
    try:
        text = render(load_entries(directory))
    except EntryError as err:
        print(f"build_projects_index: {err}", file=sys.stderr)
        return 2
    target = directory / "README.md"
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != text:
            print(f"build_projects_index: {target} is out of date; run the tool without --check", file=sys.stderr)
            return 1
        print(f"build_projects_index: {target} is current")
        return 0
    target.write_text(text, encoding="utf-8")
    print(f"build_projects_index: wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
